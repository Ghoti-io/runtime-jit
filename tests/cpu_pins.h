/**
 * @file cpu_pins.h
 *
 * The bytes of the fourteen feature-dependent operations (`clz`, `ctz`, `popcnt` at both integer widths and
 * `ceil`, `floor`, `trunc`, `nearest` at both float widths) as whole single-operation functions emitted for
 * x86-64 SysV with a request-word offset of 0x40 (spec-runtime-float, story 4).
 *
 * `v1` is the baseline commit's (`7bf1b55`, the end of story 3) own output for the same function, taken by
 * building that commit and printing the bytes, and it is what a compile with every optional feature masked
 * off must still emit: the sequences of stories 2 and 3 are unchanged. `arm` is the same function with
 * exactly the one feature the operation uses; it was read back with `objdump -D -M intel` (an `lzcnt eax, eax`,
 * `tzcnt`, `popcnt`, `roundsd/roundss xmm0, xmm0, imm` where the v1 sequence was) and is pinned so that a
 * change to either is seen.
 */

